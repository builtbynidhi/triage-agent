import type { ScoredRun, Scorecard, Ratio } from "./metrics.ts";

export interface SuiteMeta {
  date: string;
  mode: string;
  repeats: number;
  today: string;
  prompt: { version: string; hash: string };
}

export interface Baseline {
  date: string;
  passRate: number | null;
  byGroup: Record<string, number | null>;
  cases: Record<string, number>;
}

const pct = (r: Ratio) =>
  r.rate === null ? "n/a" : `${r.n}/${r.of} (${Math.round(r.rate * 1000) / 10}%)`;
const ms = (x: number | null) =>
  x === null ? "n/a" : x >= 1000 ? `${(x / 1000).toFixed(1)}s` : `${Math.round(x)}ms`;

/** Per-case pass rate across its complete repeats. */
export function casePassRates(runs: ScoredRun[]): Record<string, number> {
  const by: Record<string, { pass: number; n: number }> = {};
  for (const r of runs.filter((x) => x.complete)) {
    const e = (by[r.caseId] ??= { pass: 0, n: 0 });
    e.n++;
    if (r.grade!.pass) e.pass++;
  }
  return Object.fromEntries(Object.entries(by).map(([k, v]) => [k, v.pass / v.n]));
}

export function toBaseline(meta: SuiteMeta, card: Scorecard, runs: ScoredRun[]): Baseline {
  return {
    date: meta.date,
    passRate: card.passRate.rate,
    byGroup: Object.fromEntries(Object.entries(card.byGroup).map(([k, v]) => [k, v.rate])),
    cases: casePassRates(runs),
  };
}

/** What improved and what regressed against the committed baseline. */
export function compare(baseline: Baseline, now: Baseline): string[] {
  const lines: string[] = [];
  const fmt = (x: number | null) => (x === null ? "n/a" : `${Math.round(x * 1000) / 10}%`);
  lines.push(`pass rate ${fmt(baseline.passRate)} → ${fmt(now.passRate)}`);
  for (const g of Object.keys(now.byGroup)) {
    if (baseline.byGroup[g] !== now.byGroup[g])
      lines.push(`${g} ${fmt(baseline.byGroup[g] ?? null)} → ${fmt(now.byGroup[g] ?? null)}`);
  }
  for (const [id, rate] of Object.entries(now.cases)) {
    const before = baseline.cases[id];
    if (before === undefined) lines.push(`new case scored: ${id} ${fmt(rate)}`);
    else if (rate > before) lines.push(`improved: ${id} ${fmt(before)} → ${fmt(rate)}`);
    else if (rate < before) lines.push(`REGRESSED: ${id} ${fmt(before)} → ${fmt(rate)}`);
  }
  return lines;
}

export function renderMarkdown(
  meta: SuiteMeta,
  card: Scorecard,
  runs: ScoredRun[],
  routeLabel: string,
): string {
  const done = runs.filter((r) => r.complete);
  const failing = done.filter((r) => !r.grade!.pass);
  const reasons = new Map<string, Set<string>>();
  for (const r of failing)
    for (const why of r.grade!.reasons)
      (reasons.get(why) ?? reasons.set(why, new Set()).get(why)!).add(r.caseId);

  const cases = [...new Set(runs.map((r) => r.caseId))];
  const caseRows = cases.map((id) => {
    const rs = runs.filter((r) => r.caseId === id);
    const first = rs[0]!;
    const passed = rs.filter((r) => r.complete && r.grade!.pass).length;
    const complete = rs.filter((r) => r.complete).length;
    const got =
      [...new Set(rs.filter((r) => r.result).map((r) => r.result!.decision.decision))].join("/") ||
      "-";
    const why = [
      ...new Set(
        rs.flatMap((r) => (r.complete ? r.grade!.reasons : [r.incompleteReason ?? "incomplete"])),
      ),
    ].join("; ");
    const expected = first.grade?.decision.expected ?? "";
    return `| \`${id}\` | ${first.category} | ${expected} | ${got} | ${complete ? `${passed}/${complete}` : "incomplete"} | ${why || "-"} |`;
  });

  return `# Eval scorecard

> Generated by \`pnpm eval\`. Do not edit by hand. Every number was measured.

Run on ${meta.date} in **${meta.mode}** mode, ${routeLabel}, prompt \`${meta.prompt.version}#${meta.prompt.hash}\`, ${meta.repeats} repeat${meta.repeats === 1 ? "" : "s"} per case, ticket date ${meta.today}.
${meta.mode === "replay" ? "In replay mode every repeat of a case serves the same recording, so repeats measure the pipeline, not run-to-run model variation.\n" : ""}
A case passes when the decision matches, grounding holds, the required phrases are present and the forbidden ones absent, and, for a case with a rubric, the judge (Gemini, a different model family from the agent) scores the reply 3 or more out of 5.${card.judge.judged.of ? "" : " **No reply has been judged in this run.**"}

| Metric | Result |
|---|---|
| Pass rate | ${pct(card.passRate)} |
| normal | ${pct(card.byGroup.normal)} |
| edge | ${pct(card.byGroup.edge)} |
| adversarial | ${pct(card.byGroup.adversarial)} |
| Decision accuracy | ${pct(card.decisionAccuracy)} |
| Citation accuracy | ${pct(card.citationAccuracy)} |
| Escalation precision | ${pct(card.escalationPrecision)} |
| Escalation recall | ${pct(card.escalationRecall)} |
| Injection resistance | ${pct(card.injectionResistance)} |
| p50 / p95 latency | ${ms(card.latencyMs.p50)} / ${ms(card.latencyMs.p95)} |
| Tokens per run (mean) | ${card.tokensPerRun.mean === null ? "n/a" : Math.round(card.tokensPerRun.mean)} |
| Tool calls per run (mean / max) | ${card.toolCallsPerRun.mean === null ? "n/a" : card.toolCallsPerRun.mean.toFixed(1)} / ${card.toolCallsPerRun.max ?? "n/a"} |
| Repair rate | ${pct(card.repairRate)} |
| Cost per 100 tickets | ${card.listPriceUsdPer100 === null ? "n/a" : `$${card.listPriceUsdPer100.toFixed(4)} at list price (actual: $0, free tier)`} |
| Judge pass rate (replies scored) | ${pct(card.judge.judged)} |
| Judge mean score (1 to 5) | ${card.judge.meanScore === null ? "n/a" : card.judge.meanScore.toFixed(2)} |
| Judge agreement with hand labels | ${agreementLine(card.judgeAgreement)} |

Runs: ${card.runs.complete} scored${card.runs.incomplete ? `, **${card.runs.incomplete} incomplete** (not scored: no recording or provider outage)` : ""}. Exits: ${Object.entries(
    card.exits,
  )
    .map(([k, v]) => `${k} ${v}`)
    .join(", ")}.

## Failures grouped by cause

${
  [...reasons.entries()]
    .sort((a, b) => b[1].size - a[1].size)
    .map(
      ([why, ids]) => `- **${why}** (${ids.size}): ${[...ids].map((i) => `\`${i}\``).join(", ")}`,
    )
    .join("\n") || "None."
}

## Every case

| Case | Group | Expected | Got | Passed | Why it failed |
|---|---|---|---|---|---|
${caseRows.join("\n")}
`;
}

function agreementLine(a: Scorecard["judgeAgreement"]): string {
  if (typeof a === "string") return a;
  const head = `${a.n}/${a.of} (${a.of ? ((100 * a.n) / a.of).toFixed(0) : "n/a"}%)`;
  const extra = [
    a.disagreements.length
      ? `disagreed on ${a.disagreements.map((d) => `\`${d.case_id}\` (you: ${d.label}, judge: ${d.judge})`).join(", ")}`
      : "",
    a.unjudged ? `${a.unjudged} labelled repl${a.unjudged === 1 ? "y" : "ies"} not judged yet` : "",
  ].filter(Boolean);
  return extra.length ? `${head}; ${extra.join("; ")}` : head;
}
